//relational operators in javascript
let a = 9;
let b = 4;
let c = 11;
let d = 9;

console.log(a>b); //true
console.log(a>c); //false
console.log(a>d); //false

console.log(a<b); //false
console.log(a<c); //true
console.log(a<d); //false

console.log(a>=b); //true
console.log(a<=b); //false
console.log(9==9); //true
console.log(9=='9'); //true
console.log(9===9); //true
console.log(9==='9'); //false