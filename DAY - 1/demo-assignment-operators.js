//compound assignment operator in JavaScript

let s = 10, t = 20;

s += t; // s = s + t
console.log(s); 

s -= t; // s = s - t
console.log(s);

s *= t; // s = s * t
console.log(s);

s /= t; // s = s / t
console.log(s);

s %= t; // s = s % t
console.log(s);

s **= t; // s = s ** t
console.log(s);



