let foodItem = "pasta";

switch (foodItem) {
    case "pasta":
        console.log("here is your pasta!!");
        break;
    case "burger":
        console.log("here is your burger");
        break;
    case "sandwich":
        console.log("here is your sandwich");
        break;
    case "hotdog":
        console.log("here is your hotdog");
        break;
    default:
        console.log("we only serve pasta,burger,sandwich and hotdog");
        break;
}